-- ============================================================
-- 点赞状态切换（原子）
--
-- 为什么不在 Java 里"先查 score 再决定点赞还是取消"：
--   那是典型的读-改-写竞态。两个请求都读到 score == nil，都认为自己在点赞；
--   ZADD 幂等只留一条，但两边都会执行 liked = liked + 1，1 个人点出 2 个赞。
--   第一版改成 ZADD NX 判返回值，解决了计数漂移，但"这次是点还是取消"仍然在
--   Lua 外面读：并发下 A 刚点上，B 读到已点赞就去取消，净变化变成 0，
--   一个人连点 5 次可能既没点上也没取消。
--
-- 所以把"读状态 + 切换"一起放进脚本：Redis 单线程执行，读到的就是切换前的
-- 真实状态，返回的 newState 就是切换后的状态。Java 只按这个值改 DB 计数，
-- 一次请求对应一次状态翻转，不存在中间态。
--
-- KEYS[1] = blog:liked:{blogId}
-- ARGV[1] = userId
-- ARGV[2] = 时间戳（点赞列表按它倒序）
--
-- 返回：1 = 现在是已点赞；0 = 现在是未点赞
-- ============================================================
if redis.call('ZSCORE', KEYS[1], ARGV[1]) then
    redis.call('ZREM', KEYS[1], ARGV[1])
    return 0
else
    redis.call('ZADD', KEYS[1], ARGV[2], ARGV[1])
    return 1
end
